import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const sourceDir = path.join(rootDir, 'source');
const prodDir = path.join(rootDir, 'deployable');
const devDir = path.join(rootDir, 'dev');
const zipPath = path.join(rootDir, 'scamhisn-extension-prod.zip');

function copyDirRecursive(src, dest, excludeRelPaths = new Set(), base = src) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    // Forward slashes on every OS, so the exclude list below also matches on Windows
    const relPath = path.relative(base, srcPath).split(path.sep).join('/');
    if (excludeRelPaths.has(relPath)) continue;
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath, excludeRelPaths, base);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function buildTarget({ outDir, isDev }) {
  fs.rmSync(outDir, { recursive: true, force: true });

  // Version 2: Check Everything ships in the public build too, so both builds carry content.js.
  // The user still has to switch it on in the popup; it is off by default.
  copyDirRecursive(sourceDir, outDir, new Set());

  // Write environment-specific config.js
  const configContent = `// Auto-generated by scripts/build.mjs (${isDev ? 'PRIVATE DEV' : 'PRODUCTION'})
export const EXTENSION_CONFIG = {
  // True in both builds since version 2: it unlocks Check Everything (automatic link checks)
  DEV_MODE: true,
  // Shows the DEV label and talks to a local server only in the private build
  PRIVATE_BUILD: ${isDev ? 'true' : 'false'},
  DEFAULT_API_BASE: '${isDev ? 'http://localhost:3001' : 'https://scamhisn-ai-v2.onrender.com'}',
  MAX_AUTO_LINKS_PER_PAGE: 6,
};
`;
  fs.writeFileSync(path.join(outDir, 'src/config.js'), configContent, 'utf8');

  // Write environment-specific manifest.json
  const manifest = JSON.parse(fs.readFileSync(path.join(sourceDir, 'manifest.json'), 'utf8'));
  // Check Everything needs the page script in both builds
  manifest.content_scripts = [
    {
      matches: ['http://*/*', 'https://*/*'],
      js: ['src/content.js'],
      run_at: 'document_idle',
    },
  ];
  if (isDev) {
    manifest.name = 'ScamHisn AI (DEV — Private Testing)';
  } else {
    // Production strictly strips localhost host permission and keeps minimal permissions
    manifest.host_permissions = ['https://*.onrender.com/*'];
  }

  fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
}

buildTarget({ outDir: prodDir, isDev: false });
buildTarget({ outDir: devDir, isDev: true });

/**
 * Minimal ZIP writer (deflate, forward-slash paths) so the build works on Windows, macOS and
 * Linux without the `zip` command-line tool. Timestamps are fixed, so the same input always
 * produces the same archive.
 */
function listFiles(dir, base = dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      return entry.isDirectory()
        ? listFiles(full, base)
        : [{ full, name: path.relative(base, full).split(path.sep).join('/') }];
    });
}

function writeZip(sourceDir, outPath) {
  const DOS_TIME = 0; // 00:00:00
  const DOS_DATE = ((2026 - 1980) << 9) | (1 << 5) | 1; // 2026-01-01
  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const file of listFiles(sourceDir)) {
    const data = fs.readFileSync(file.full);
    const compressed = zlib.deflateRawSync(data, { level: 9 });
    const name = Buffer.from(file.name, 'utf8');
    const crc = zlib.crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(8, 8); // deflate
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    localParts.push(local, name, compressed);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4); // version made by
    central.writeUInt16LE(20, 6); // version needed
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    centralParts.push(central, name);

    offset += local.length + name.length + compressed.length;
  }

  const centralDir = Buffer.concat(centralParts);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(centralParts.length / 2, 8);
  end.writeUInt16LE(centralParts.length / 2, 10);
  end.writeUInt32LE(centralDir.length, 12);
  end.writeUInt32LE(offset, 16);
  fs.writeFileSync(outPath, Buffer.concat([...localParts, centralDir, end]));
}

// Package deployable/ as a Chrome Web Store ready .zip, and refresh the copy the website serves
fs.rmSync(zipPath, { force: true });
writeZip(prodDir, zipPath);

const webCopy = path.resolve(rootDir, '../Deployable Website Application/apps/web/public/scamhisn-extension.zip');
if (fs.existsSync(path.dirname(webCopy))) {
  fs.copyFileSync(zipPath, webCopy);
  console.log('✓ Updated website download:', webCopy);
}

console.log('✓ Built production extension:', prodDir);
console.log('✓ Built private dev extension:', devDir);
console.log('✓ Packaged Chrome Web Store zip:', zipPath);
